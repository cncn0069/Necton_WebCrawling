    # "외교부가 군사대비태세 문서를 쓴다" 같은 시나리오-기관 불일치를 막을 수 있다
    # (2026-07-21 사용자 지적으로 스코프 재확정 — 이전엔 조항 단위 랜덤만 허용했었다).
